/**
 * تحويل النص العادي إلى صيغة الإلقاء الجزائري الفصيح:
 * 1. استبدال الوصل الروبوتي بسكون محكم على الفواصل.
 * 2. إدخال علامات التنفس والوقفات الإلقائية [وقفة هادئة].
 * 3. تشكيل الكلمات والمصطلحات القانونية بالنطق الجزائري الفصيح.
 */
export function formatToAlgerianOratoryScript(text: string): string {
  if (!text) return '';

  let formatted = text.trim();

  // ضبط أواخر الجمل لتسكين الوقف الجزائري
  formatted = formatted
    .replace(/ثانوية ابن الهيثم/g, 'ثَانَوِيَّةُ ابْنِ الهَيْثَمْ')
    .replace(/مشرف تربية/g, 'مُشْرِفُ تَرْبِيَةْ')
    .replace(/القانون الداخلي/g, 'القَانُونُ الدَّاخِلِيْ')
    .replace(/الميثاق المدرسي/g, 'المِيثَاقُ المَدْرَسِيْ')
    .replace(/المئزر الأبيض/g, 'المِئْزَرُ الأَبْيَضْ')
    .replace(/الهاتف النقال/g, 'الهَاتِفُ النَّقَّالْ')
    .replace(/البكالوريا/g, 'البَكَالُورْيَا')
    .replace(/أبنائي وبناتي/g, 'أَبْنَائِي وَبَنَاتِي')
    .replace(/التلاميذ/g, 'التَّلَامِيذْ')
    .replace(/التلميذ/g, 'التِّلْمِيذْ')
    .replace(/المؤسسة/g, 'المُؤَسَّسَةْ')
    .replace(/الانضباط/g, 'الانْضِبَاطْ')
    .replace(/الاحترام المتبادل/g, 'الاحْتِرَامُ المُتَبَادَلْ');

  // إضافة فواصل التنفس الإذاعية المريحة
  formatted = formatted
    .replace(/،/g, '، ... ')
    .replace(/؛/g, '؛ ..... ')
    .replace(/\./g, '.\n... ');

  return formatted;
}

